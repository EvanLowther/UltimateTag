"""Uploads the rendered icons to Roblox with Open Cloud and writes their image ids for the game.

Run it yourself, with your own API key in the environment (never paste the key anywhere else):

    export ROBLOX_API_KEY=...        # create.roblox.com > Open Cloud > API Keys (see below)
    export ROBLOX_USER_ID=...        # your user id (the number in your profile's URL)
    node tools/icons/render.mjs build/icons
    python3 tools/icons/upload.py build/icons

The key needs two permissions: Assets (read and write), to upload, and Legacy Assets
(legacy-asset:manage), to look up each upload's image. Open Cloud uploads a PNG as a Decal and
returns the decal's id, but an ImageLabel needs the image inside it, so each decal is looked up
once through the Asset Delivery API to find it.

Ids land in tools/icons/asset_ids.json ({"shop": {"decal": ..., "image": ...}, ...}) and the
image ids in src/shared/IconImages.luau, which the game reads (Config.Icons.Images). Icons
already uploaded are skipped and lookups that failed are tried again, so it can be run again
after a failure. To redo an icon: change it, render, delete its line from asset_ids.json, run
this again. Only the Python standard library is used.
"""

from __future__ import annotations

import gzip
import json
import os
import re
import sys
import time
import urllib.error
import urllib.request
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
IDS = os.path.join(HERE, "asset_ids.json")
LUAU = os.path.join(ROOT, "src", "shared", "IconImages.luau")
ASSETS = "https://apis.roblox.com/assets/v1"
DELIVERY = "https://apis.roblox.com/asset-delivery-api/v1/assetId"


def request(method: str, url: str, key: str | None, body: bytes | None = None, ctype: str | None = None) -> bytes:
    req = urllib.request.Request(url, data=body, method=method)
    if key:
        req.add_header("x-api-key", key)
    if ctype:
        req.add_header("Content-Type", ctype)
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            data = r.read()
    except urllib.error.HTTPError as e:
        raise RuntimeError(f"{e.code} {e.reason}: {e.read().decode(errors='replace')[:300]}") from None
    return gzip.decompress(data) if data[:2] == b"\x1f\x8b" else data


def upload(path: str, name: str, key: str, user: str) -> int:
    meta = {
        "assetType": "Decal",
        "displayName": name,
        "description": "Ultimate Tag icon",
        "creationContext": {"creator": {"userId": user}},
    }
    boundary = uuid.uuid4().hex
    with open(path, "rb") as f:
        data = f.read()
    body = (
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"request\"\r\n"
        f"Content-Type: application/json\r\n\r\n{json.dumps(meta)}\r\n"
        f"--{boundary}\r\nContent-Disposition: form-data; name=\"fileContent\"; filename=\"{os.path.basename(path)}\"\r\n"
        f"Content-Type: image/png\r\n\r\n"
    ).encode() + data + f"\r\n--{boundary}--\r\n".encode()
    op = json.loads(request("POST", f"{ASSETS}/assets", key, body, f"multipart/form-data; boundary={boundary}") or b"{}")
    op_id = op.get("operationId") or op.get("path", "").split("/")[-1]
    for _ in range(60):
        if op.get("done"):
            break
        time.sleep(2)
        op = json.loads(request("GET", f"{ASSETS}/operations/{op_id}", key) or b"{}")
    if not op.get("done"):
        raise RuntimeError("still processing after 2 minutes; run the script again later")
    if "error" in op:
        raise RuntimeError(json.dumps(op["error"]))
    return int(op["response"]["assetId"])


def image_of(decal: int, key: str) -> int:
    """The image inside a decal: the decal's file (a small model) names its texture."""
    info = json.loads(request("GET", f"{DELIVERY}/{decal}", key) or b"{}")
    location = info.get("location")
    if not location:
        raise RuntimeError(f"no download location: {json.dumps(info)[:200]}")
    content = request("GET", location, None)
    found = re.search(rb"(?:asset/\?id=|rbxassetid://)(\d+)", content)
    if not found:
        raise RuntimeError("the decal's file names no image")
    return int(found.group(1))


def write_luau(ids: dict) -> None:
    lines = [
        "--!strict",
        "-- Generated by tools/icons/upload.py: the uploaded image for each icon (client/Icons reads it",
        "-- through Config.Icons.Images). Don't edit by hand; run the script again instead.",
        "return {",
    ]
    for name in sorted(ids):
        image = ids[name].get("image")
        if image:
            lines.append(f"\t{name} = {image},")
    lines.append("} :: { [string]: number }")
    with open(LUAU, "w") as f:
        f.write("\n".join(lines) + "\n")


def main() -> None:
    folder = sys.argv[1] if len(sys.argv) > 1 else "build/icons"
    key = os.environ.get("ROBLOX_API_KEY")
    user = os.environ.get("ROBLOX_USER_ID")
    if not key or not user:
        sys.exit("Set ROBLOX_API_KEY and ROBLOX_USER_ID first (see the top of this file).")
    ids: dict = {}
    if os.path.exists(IDS):
        with open(IDS) as f:
            ids = json.load(f)
    with open(os.path.join(folder, "files.txt")) as f:
        files = [line.strip() for line in f if line.strip()]
    failed = 0
    for i, file in enumerate(files, 1):
        name = file.removesuffix(".png")
        entry = ids.setdefault(name, {})
        try:
            if "decal" not in entry:
                entry["decal"] = upload(os.path.join(folder, "png", file), f"UT_icon_{name}", key, user)
            if "image" not in entry:
                entry["image"] = image_of(entry["decal"], key)
            print(f"[{i}/{len(files)}] {name}: image {entry['image']}")
        except Exception as e:  # keep going; a second run retries what failed
            failed += 1
            print(f"[{i}/{len(files)}] {name}: FAILED {e}")
        if not entry:
            del ids[name]
        with open(IDS, "w") as f:
            json.dump(dict(sorted(ids.items())), f, indent=1)
        time.sleep(0.3)
    write_luau(ids)
    ready = sum(1 for e in ids.values() if e.get("image"))
    print(f"done: {ready} of {len(files)} icons have images (src/shared/IconImages.luau)")
    if failed:
        print(f"{failed} failed: run it again to retry. If the lookups fail with 401 or 403, give the key the")
        print("Legacy Assets permission (legacy-asset:manage) and run it again; uploads already done are kept.")


if __name__ == "__main__":
    main()
